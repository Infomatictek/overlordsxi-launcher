assert(M.decide(live, 'terramancer', 'spell', 161, 29) == 'hide')
assert(M.decide(live, 'terramancer', 'spell', 161, 30) == 'show')
assert(M.decide(live, 'diviner',     'spell', 160, 30) == 'unmanaged')
assert(M.decide(live, 'shinobi',     'spell', 339, 36) == 'hide')
assert(M.decide(live, 'shinobi',     'spell', 339, 37) == 'show')
assert(M.decide(live, 'kagemusha',   'spell', 339, 10) == 'show')
assert(M.decide(live, 'kagemusha',   'spell', 320, 10) == 'show')
assert(M.decide(live, 'kagemusha',   'spell', 347, 10) == 'show')
assert(M.decide(live, 'dreadnought', 'spell', 246, 9)  == 'hide')
assert(M.decide(live, 'dreadnought', 'spell', 246, 10) == 'show')
assert(M.decide(live, 'dreadnought', 'spell', 277, 10) == 'show')
assert(M.decide(live, 'reaper',      'spell', 246, 10) == 'unmanaged')
assert(M.decide(live, 'magus',       'spell', 593, 10) == 'show')
assert(M.decide(live, 'magus',       'spell', 690, 10) == 'show')
assert(M.decide(live, 'magus',       'spell', 692, 10) == 'show')
assert(M.decide(live, 'warmage',     'spell', 593, 10) == 'unmanaged')
