package.path = './?.lua;' .. package.path
local catalog = require('catalog')
local builtins = require('builtin_profiles')
assert(builtins.install(catalog) == 10)
assert(catalog.get('shinobi', 'spell', 338).name == 'Shadow Squadron: Ichi')
assert(catalog.get('shinobi', 'spell', 339).name == 'Shadow Squadron: Ni')
assert(catalog.get('shinobi', 'spell', 320).name == 'False Assault')
assert(catalog.get('shinobi', 'spell', 323).name == 'Mirror Step')
assert(catalog.get('shinobi', 'spell', 326).name == 'Crosscut')
assert(catalog.get('shinobi', 'spell', 329).name == 'Shadow Pin')
assert(catalog.get('shinobi', 'spell', 332).name == 'Thunder Relay')
assert(catalog.get('shinobi', 'spell', 335).name == 'Final Mirage')
assert(catalog.get('shinobi', 'ability', 999).name == 'Shadow Legion')
assert(catalog.get('shinobi', 'ability', 1000).name == 'Phantom Assault')
assert(catalog.get('shinobi', 'spell', 338).description:find('2 offensive shadow clones', 1, true))
assert(catalog.get('shinobi', 'spell', 339).description:find('3 offensive shadow clones', 1, true))
for _, id in ipairs({ 320, 323, 326, 329, 332, 335 }) do
    assert(not catalog.get('shinobi', 'spell', id).description:find('Prototype', 1, true))
end
assert(catalog.get('kagemusha', 'spell', 338) == nil)
assert(catalog.get('shinobi', 'spell', 340) == nil)
assert(catalog.get('shinobi', 'ability', 338) == nil)
catalog.clear()
assert(builtins.install(catalog) == 10)
print('Shinobi 2.0 action identity tests passed.')
